public class UnaryOperator {
    public static void main(String[] args) {
        int p =5 ;


      System.out.println(p);
      //5
      System.out.println(p++);
      //5
      System.out.println(p);
      //6
      System.out.println(++p);
      //7
      System.out.println(--p);
      //6
      System.out.println(p--);
      //6
      System.out.println(p);
      //5
        }

}